"""Convert continuous wall atlas records into GLB UV mapping format.

Keeps primitive/index provenance from triangle input and assigns the atlas
coordinates generated by the wall atlas stage.
"""

import argparse
import json
from pathlib import Path


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--atlas", required=True)
    p.add_argument("--triangles", required=True)
    p.add_argument("--size", type=int, default=4096)
    p.add_argument("--output", required=True)
    args = p.parse_args()

    atlas = json.loads(Path(args.atlas).read_text(encoding="utf-8"))
    triangles = {int(t["id"]): t for t in json.loads(Path(args.triangles).read_text(encoding="utf-8"))["triangles"]}

    mappings = []
    for record in atlas.get("records", []):
        tri = triangles.get(int(record["triangleId"]))
        if not tri:
            continue
        s = args.size
        uv = record.get("atlasUV")
        if not uv:
            continue
        mappings.append({
            "triangleId": str(record["triangleId"]),
            "primitiveId": tri.get("primitiveId"),
            "indexOffset": tri.get("indexOffset"),
            "vertexIds": tri.get("vertexIds"),
            "sourceId": record.get("sourceId"),
            "atlasUV": uv,
        })

    Path(args.output).write_text(json.dumps({
        "status": "wall-atlas-mapping-generated",
        "mappings": mappings,
    }, indent=2), encoding="utf-8")
    print(json.dumps({"status": "wall-atlas-mapping-generated", "mappingCount": len(mappings)}))


if __name__ == "__main__":
    main()
