// Apply atlas texture and generated triangle UV mappings to a GLB.
// The mapping file is kept as the source of truth for provenance audits.

import { readFile, writeFile } from 'node:fs/promises';
import { NodeIO } from '@gltf-transform/core';
import { EXTMeshoptCompression } from '@gltf-transform/extensions';
import { MeshoptDecoder, MeshoptEncoder } from 'meshoptimizer';

const [input, atlasFile, mappingFile, output] = process.argv.slice(2);
if (!input || !atlasFile || !mappingFile || !output) {
  console.error('Usage: node texture-building-apply-atlas.mjs input.glb atlas.png mapping.json output.glb');
  process.exit(1);
}

const mapping = JSON.parse(await readFile(mappingFile, 'utf8'));
const byTriangle = new Map();
for (const m of mapping.mappings) {
  const offset = m.indexOffset ?? (m.triangleId * 3);
  byTriangle.set(`${m.meshIndex ?? 0}:${m.primitiveId ?? 0}:${offset}`, m);
  // Some landmark exports intentionally omit meshIndex because the source
  // triangle stream was generated before GLTF mesh splitting. Preserve that
  // provenance by allowing the original primitive triangle offset to resolve.
  byTriangle.set(`${m.primitiveId ?? 0}:${offset}`, m);
  byTriangle.set(`${offset}`, m);
}
const io = new NodeIO()
  .registerExtensions([EXTMeshoptCompression])
  .registerDependencies({ 'meshopt.decoder': MeshoptDecoder, 'meshopt.encoder': MeshoptEncoder });
const doc = await io.read(input);
const texture = doc.createTexture('photographic-landmark-atlas')
  .setImage(await readFile(atlasFile))
  .setMimeType('image/png');
// Keep the source PBR response. The atlas only replaces the albedo source;
// forcing KHR_materials_unlit here removes the lighting response of the
// original PLATEAU materials and creates dark surfaces in normal viewers.
const materialCache = new Map();
function atlasMaterial(sourceMaterial) {
  if (!sourceMaterial) return sourceMaterial;
  if (materialCache.has(sourceMaterial)) return materialCache.get(sourceMaterial);
  const m = doc.createMaterial(`${sourceMaterial.getName() || 'material'}-photographic-atlas`);
  m.setBaseColorTexture(texture)
    .setDoubleSided(sourceMaterial.getDoubleSided());
  if (sourceMaterial.getMetallicFactor() !== null) m.setMetallicFactor(sourceMaterial.getMetallicFactor());
  if (sourceMaterial.getRoughnessFactor() !== null) m.setRoughnessFactor(sourceMaterial.getRoughnessFactor());
  materialCache.set(sourceMaterial, m);
  return m;
}

let primitivesUpdated = 0;
let uvMappingsAvailable = 0;
let skippedPrimitives = 0;
const meshIndexByMesh = new Map(doc.getRoot().listMeshes().map((mesh, index) => [mesh, index]));

// GLTF primitive triangle ordering is retained for models generated by the
// landmark pipeline. Unknown primitives are skipped instead of receiving a
// texture with unverified correspondence.
for (const node of doc.getRoot().listNodes()) {
  const mesh = node.getMesh();
  const meshIndex = meshIndexByMesh.get(mesh);
  if (meshIndex === undefined) continue;
  // Work on a snapshot. New split primitives must not be visited by this loop.
  const sourcePrimitives = [...(mesh.listPrimitives() ?? [])];
  for (const [primitiveId, primitive] of sourcePrimitives.entries()) {
    const index = primitive.getIndices();
    const uv = primitive.getAttribute('TEXCOORD_0');
    if (!index || !uv) continue;

    let mapped = 0;
    const pending = [];
    for (let i = 0; i < index.getCount(); i += 3) {
      const triangle = byTriangle.get(`${meshIndex}:${primitiveId}:${i}`)
        ?? byTriangle.get(`${primitiveId}:${i}`)
        ?? byTriangle.get(`${i}`);
      if (!triangle) continue;
      const vertices = [index.getScalar(i), index.getScalar(i + 1), index.getScalar(i + 2)];
      pending.push({triangle, vertices});
      mapped++;
    }
    if (mapped > 0) {
      const photoTriangles = new Map(pending.map(({triangle, vertices}) => [vertices.join(','), triangle]));
      const groups = [[], []];
      for (let i = 0; i < index.getCount(); i += 3) {
        const ids = [index.getScalar(i), index.getScalar(i + 1), index.getScalar(i + 2)];
        groups[photoTriangles.has(ids.join(',')) ? 0 : 1].push(ids);
      }

      for (const [groupId, triangles] of groups.entries()) {
        if (!triangles.length) continue;
        const outputPrimitive = doc.createPrimitive().setMode(primitive.getMode());
        // Build vertices per triangle corner. A GLTF vertex can only have one
        // TEXCOORD_0 value, while photographic atlas projection assigns UVs
        // per triangle corner. Reusing the original vertex index causes UV
        // conflicts and corrupts the primitive after export.
        const localVertices = [];
        const outputIndexArray = [];
        const triangleMappings = [];
        for (let triangleNo = 0; triangleNo < triangles.length; triangleNo++) {
          const triangle = triangles[triangleNo];
          const mappedTriangle = pending.find(p => p.vertices.join(',') === triangle.join(','))?.triangle;
          for (const vertex of triangle) {
            outputIndexArray.push(localVertices.length);
            // Keep one exported vertex per triangle corner. A GLTF vertex
            // carries a single UV value, while the photo atlas mapping is
            // defined per corner. Reusing the original vertex index creates
            // invalid shared attribute relationships.
            localVertices.push({vertex, mappedTriangle, corner: localVertices.length % 3});
          }
          triangleMappings.push(mappedTriangle);
        }
        for (const semantic of primitive.listSemantics()) {
          const source = primitive.getAttribute(semantic);
          const values = [];
          for (const [corner, item] of localVertices.entries()) {
              const vertex = item.vertex;
              if (semantic === 'TEXCOORD_0' && groupId === 0) {
                const mappedTriangle = item.mappedTriangle;
                const cornerIndex = item.corner;
                const vertexOffset = cornerIndex;
                if (mappedTriangle && vertexOffset >= 0) {
                  values.push(mappedTriangle.atlasUV[vertexOffset][0]);
                  values.push(mappedTriangle.atlasUV[vertexOffset][1]);
                  continue;
                }
                values.push(...source.getElement(vertex, []));
              } else {
                values.push(...source.getElement(vertex, []));
              }
          }
          outputPrimitive.setAttribute(semantic, doc.createAccessor()
            .setType(source.getType())
            .setArray(new (source.getArray().constructor)(values)));
        }
        outputPrimitive.setIndices(doc.createAccessor()
          .setType('SCALAR')
          .setArray(new Uint32Array(outputIndexArray)));
        outputPrimitive.setMaterial(groupId === 0 ? atlasMaterial(primitive.getMaterial()) : primitive.getMaterial());
        mesh.addPrimitive(outputPrimitive);
      }
      mesh.removePrimitive(primitive);
      primitivesUpdated++;
      uvMappingsAvailable += mapped;
    } else {
      skippedPrimitives++;
    }
  }
}

await io.write(output, doc);
await writeFile(`${output}.atlas-report.json`, JSON.stringify({
  status: 'atlas-uv-applied',
  primitivesUpdated,
  uvMappingsAvailable,
  skippedPrimitives,
}, null, 2));
console.log(JSON.stringify({ status: 'atlas-uv-applied', primitivesUpdated, uvMappingsAvailable, skippedPrimitives }));
